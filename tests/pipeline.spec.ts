import { test, expect, expectNoOverflow } from './helpers.ts'

test.describe('local CI/CD administration', () => {
  test.use({ anonymous: true })
  test.beforeEach(async ({ page, request }) => {
    expect((await request.post('/__test/admin-bootstrap')).status()).toBe(204)
    expect((await request.post('/api/auth/login', { data: { method: 'username', identifier: 'wxpwindy', password: 'Example123' } })).status()).toBe(200)
    expect((await request.post('/api/auth/change-password', { data: { currentPassword: 'Example123', newPassword: 'Fictional-pipeline-password-2026!' } })).status()).toBe(200)
    await page.reload()
    await page.getByRole('button', { name: 'Administration', exact: true }).click()
  })

  test('runs, shows logs, deploys two tested releases and rolls back at 320px', async ({ page, request }, testInfo) => {
    const panel = page.getByRole('region', { name: 'CI/CD pipeline', exact: true })
    await expect(panel.getByRole('button', { name: 'Run pipeline', exact: true })).toBeEnabled()
    await expect(panel).toContainText('Your first green build starts here')
    const ids: string[] = []
    for (let i = 0; i < 2; i++) {
      await panel.getByRole('button', { name: 'Run pipeline', exact: true }).click()
      await expect(panel.getByRole('button', { name: 'Run pipeline', exact: true })).toBeDisabled()
      await expect(panel.getByRole('button', { name: 'Cancel run', exact: true })).toBeEnabled()
      await expect(panel.getByRole('button', { name: 'Deploy web release', exact: true })).toBeDisabled()
      await expect(panel.getByLabel('Lint log', { exact: true })).toContainText('Fictional lint output.')
      const current = await (await request.get('/api/admin/pipeline')).json()
      ids.push(current.runs[0].id)
      expect((await request.post('/__test/pipeline-complete')).status()).toBe(200)
      await panel.getByRole('button', { name: 'Refresh pipeline', exact: true }).click()
      await expect(panel.getByRole('button', { name: 'Deploy web release', exact: true })).toBeEnabled()
      page.once('dialog', dialog => dialog.accept())
      await panel.getByRole('button', { name: 'Deploy web release', exact: true }).click()
      await expect(panel.getByRole('button', { name: 'Deployed', exact: true })).toBeDisabled()
      await expect(panel.locator('.pipeline-metrics')).toContainText(ids[i].slice(0, 8))
    }
    await panel.screenshot({ path: testInfo.outputPath('pipeline-dashboard.png') })
    await page.setViewportSize({ width: 320, height: 1000 })
    await expectNoOverflow(page)
    page.once('dialog', dialog => dialog.accept())
    await panel.getByRole('button', { name: 'Roll back web release', exact: true }).click()
    await expect(panel.locator('.pipeline-metrics')).toContainText(ids[0].slice(0, 8))
    await panel.getByRole('button', { name: new RegExp(`Run ${ids[0].slice(0, 8)}`) }).click()
    await expect(panel.getByRole('button', { name: 'Deployed', exact: true })).toBeDisabled()
    await page.reload()
    await page.getByRole('button', { name: 'Administration', exact: true }).click()
    await expect(panel.locator('.pipeline-metrics')).toContainText(ids[0].slice(0, 8))
    expect((await request.get('/api/workspace')).status()).toBe(200)
    await expectNoOverflow(page)
  })

  test('failed builds stay undeployable, cancellation and refresh errors are recoverable', async ({ page, request, expectedHttpErrors }) => {
    const panel = page.getByRole('region', { name: 'CI/CD pipeline', exact: true })
    await panel.getByRole('button', { name: 'Run pipeline', exact: true }).click()
    expect((await request.post('/__test/pipeline-complete', { data: { fail: true } })).status()).toBe(200)
    await panel.getByRole('button', { name: 'Refresh pipeline', exact: true }).click()
    await expect(panel.getByLabel('Lint log', { exact: true })).toContainText('Fictional lint failure.')
    await expect(panel.getByRole('button', { name: 'Deploy web release', exact: true })).toBeDisabled()
    await panel.getByRole('button', { name: 'Run pipeline', exact: true }).click()
    await panel.getByRole('button', { name: 'Cancel run', exact: true }).click()
    await expect(panel.locator('.pipeline-metrics')).toContainText('cancelled')
    await expect(panel.getByRole('button', { name: 'Run pipeline', exact: true })).toBeEnabled()
    expectedHttpErrors.push({ url: 'http://127.0.0.1:3101/api/admin/pipeline', status: 503 })
    await page.route('**/api/admin/pipeline', route => route.fulfill({ status: 503, json: { error: 'Fictional pipeline unavailable.' } }))
    await panel.getByRole('button', { name: 'Refresh pipeline', exact: true }).click()
    await expect(panel.getByRole('alert')).toContainText('Fictional pipeline unavailable.')
    await page.unroute('**/api/admin/pipeline')
    await panel.getByRole('button', { name: 'Refresh pipeline', exact: true }).click()
    await expect(panel.getByRole('alert')).toHaveCount(0)
    await expect(panel.locator('.pipeline-history .pipeline-run')).toHaveCount(2)
  })
})