import { test, expect, uploadResume, expectNoOverflow, testSettingsKey } from './helpers.ts'
import type { Workspace } from '../src/types.ts'

for (const savedModel of ['google/gemma-4-12b', 'custom-local-model']) {
  test(`E4B default migrates only the old default, preserves custom choices: ${savedModel}`, async ({ page }) => {
    await uploadResume(page)
    await page.evaluate(({ key, model }) => localStorage.setItem(key, JSON.stringify({ provider: 'lmstudio', lmstudioModel: model })), { key: testSettingsKey, model: savedModel })
    await page.route('**/api/workspace', async route => {
      const response = await route.fetch()
      const body: Workspace = await response.json()
      await route.fulfill({ response, json: { ...body, config: { ...body.config, defaultProvider: 'lmstudio', lmstudioModel: 'google/gemma-4-e4b' } } })
    })
    await page.reload()
    const expectedModel = savedModel === 'google/gemma-4-12b' ? 'google/gemma-4-e4b' : savedModel
    await page.getByRole('button', { name: 'Base resume', exact: true }).click()
    await page.getByRole('button', { name: 'Create clean English + Chinese', exact: true }).click()
    const form = page.getByRole('dialog', { name: 'Create clean base resumes' })
    await expect(form.locator('.generation-provider')).toContainText(expectedModel)
    const pending = page.waitForRequest(request => request.url().endsWith('/api/base/clean'))
    await form.getByRole('button', { name: 'Generate both versions', exact: true }).click()
    expect((await pending).postDataJSON()).toMatchObject({ provider: 'lmstudio', model: expectedModel })
    await page.getByRole('dialog', { name: 'Clean base resume', exact: true }).getByRole('button', { name: 'Close dialog', exact: true }).click()
    await page.reload()
    await page.getByRole('button', { name: 'Open AI settings', exact: true }).click()
    const settings = page.getByRole('dialog', { name: 'Your AI, your choice.' })
    await expect(settings.getByLabel('LM Studio model', { exact: true })).toHaveValue(expectedModel)
    // A deliberate later selection of the previous model must not migrate again.
    await settings.getByLabel('LM Studio model', { exact: true }).fill('google/gemma-4-12b')
    await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
    await page.reload()
    await page.getByRole('button', { name: 'Open AI settings', exact: true }).click()
    await expect(settings.getByLabel('LM Studio model', { exact: true })).toHaveValue('google/gemma-4-12b')
  })
}

test('LM Studio default migrates legacy settings, generates both clean languages and persists explicit choices', async ({ page }) => {
  await uploadResume(page)
  await page.evaluate(key => localStorage.setItem(key, JSON.stringify({ provider: 'ollama', ollamaModel: 'old-local-model' })), testSettingsKey)
  await page.route('**/api/workspace', async route => {
    const response = await route.fetch()
    const body: Workspace = await response.json()
    await route.fulfill({ response, json: { ...body, config: { ...body.config, defaultProvider: 'lmstudio' } } })
  })
  await page.reload()
  await page.getByRole('button', { name: 'Open AI settings', exact: true }).click()
  const settings = page.getByRole('dialog', { name: 'Your AI, your choice.' })
  await expect(settings.getByRole('button', { name: 'LM Studio Local & private', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(settings.getByLabel('LM Studio model', { exact: true })).toHaveValue('google/gemma-4-12b')
  await page.route('**/api/lmstudio/models', route => route.fulfill({ json: { models: ['google/gemma-4-12b'] } }))
  await settings.getByRole('button', { name: 'Check connection', exact: true }).click()
  await expect(settings.getByRole('status')).toContainText('LM Studio is connected')
  await expect(settings.getByLabel('Available LM Studio models')).toHaveValue('google/gemma-4-12b')
  await page.setViewportSize({ width: 320, height: 900 })
  await expectNoOverflow(page)
  await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
  await page.getByRole('button', { name: 'Base resume', exact: true }).click()
  await page.getByRole('button', { name: 'Create clean English + Chinese', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Create clean base resumes' })
  await expect(form.locator('.generation-provider')).toContainText('Processed locally with LM Studio')
  await expect(form.locator('.generation-provider')).toContainText('google/gemma-4-12b')
  await expect(form.getByRole('checkbox')).toHaveCount(0)
  const pending = page.waitForRequest(request => request.url().endsWith('/api/base/clean'))
  await form.getByRole('button', { name: 'Generate both versions', exact: true }).click()
  expect((await pending).postDataJSON()).toMatchObject({ provider: 'lmstudio', model: 'google/gemma-4-12b' })
  const detail = page.getByRole('dialog', { name: 'Clean base resume', exact: true })
  await expect(detail.locator('.model-credit')).toHaveText('LM Studio · google/gemma-4-12b')
  await detail.getByRole('button', { name: 'Close dialog', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Open AI settings', exact: true }).click()
  await expect(settings.getByLabel('LM Studio model', { exact: true })).toHaveValue('google/gemma-4-12b')
  await settings.getByRole('button', { name: 'Ollama Local & private', exact: true }).click()
  await expect(settings.getByLabel('Ollama model', { exact: true })).toHaveValue('old-local-model')
  await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: 'Open AI settings', exact: true }).click()
  await expect(settings.getByRole('button', { name: 'Ollama Local & private', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('LM Studio manual selection applies to tailoring and translation without cloud consent', async ({ page }) => {
  await uploadResume(page)
  await page.getByRole('button', { name: 'Open AI settings', exact: true }).click()
  const settings = page.getByRole('dialog', { name: 'Your AI, your choice.' })
  await settings.getByRole('button', { name: 'LM Studio Local & private', exact: true }).click()
  await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
  await page.getByRole('button', { name: 'New version', exact: true }).click()
  const tailoring = page.getByRole('dialog', { name: 'A resume for your next chapter.' })
  await expect(tailoring.locator('.generation-provider')).toContainText('Processed locally with LM Studio')
  await expect(tailoring.getByRole('checkbox')).toHaveCount(0)
  await tailoring.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Translate to Chinese', exact: true }).click()
  const translation = page.getByRole('dialog', { name: 'Translate document', exact: true })
  await expect(translation.locator('.generation-provider')).toContainText('Processed locally with LM Studio')
  await expect(translation.getByRole('checkbox')).toHaveCount(0)
  const pending = page.waitForRequest(request => request.url().endsWith('/api/translations'))
  await translation.getByRole('button', { name: 'Translate document', exact: true }).click()
  const body = (await pending).postDataJSON()
  expect(body).toMatchObject({ provider: 'lmstudio', model: 'google/gemma-4-12b' })
  expect(body.apiKey).toBeUndefined()
  expect(body.cloudConsent).toBeUndefined()
  await expect(page.getByRole('dialog', { name: 'Base resume', exact: true }).locator('.model-credit')).toHaveText('LM Studio · google/gemma-4-12b')
})