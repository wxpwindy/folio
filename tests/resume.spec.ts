async function expectResumeDownload(page: Page, detail: Locator, filename: string, text: string) {
  const downloaded = page.waitForEvent('download')
  await detail.getByRole('button', { name: 'Export PDF', exact: true }).click()
  const download = await downloaded
  expect(download.suggestedFilename()).toBe(filename)
  const buffer = await readFile((await download.path())!)
  expect(buffer.subarray(0, 5).toString()).toBe('%PDF-')
  const parser = new PDFParse({ data: new Uint8Array(buffer) })
  try {
    const parsed = await parser.getText({ pageJoiner: '\n' })
    // Ignore PDF line wrapping, but require every character (including accents,
    // curly apostrophes and em dashes) from the independently saved draft.
    expect(parsed.text.replace(/\s+/g, ' ').trim()).toContain(text.replace(/\s+/g, ' ').trim())
  } finally {
    await parser.destroy()
  }
}

async function expectCoverLetterLayout(page: Page) {
  await expectNoOverflow(page)
  // Catch nested horizontal scrolling too, not just document-level overflow.
  const overflow = await page.locator('main, .header-actions, .filter-bar, .version-card, dialog[open] .modal-body, dialog[open] .tabs, dialog[open] .modal-footer, dialog[open] .resume-editor, dialog[open] .language-toolbar').evaluateAll(elements =>
    elements.filter(element => element.scrollWidth > element.clientWidth + 1).map(element => element.className))
  expect(overflow).toEqual([])
  for (const control of await page.locator('dialog[open] input:visible, dialog[open] select:visible, dialog[open] textarea:visible, .filter-bar select:visible').all()) {
    const bounds = await control.boundingBox()
    expect(bounds).not.toBeNull()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  }
}

