test('paired switch cancels or discards unsaved changes and only links the same generation', async ({ page, request }) => {
  await uploadResume(page)
  const detail = await createVersion(page, 'Frontend Engineer', 'Example Labs', frenchJobDescription)
  const firstWorkspace: Workspace = await (await request.get('/api/workspace')).json()
  const firstPair = firstWorkspace.versions
  expect(firstPair).toHaveLength(2)
  await detail.getByRole('button', { name: 'Close dialog' }).click()
  // Deliberately use identical role/company so pairing cannot rely on their labels.
  await createVersion(page, 'Frontend Engineer', 'Example Labs', frenchJobDescription)
  const workspace: Workspace = await (await request.get('/api/workspace')).json()
  expect(workspace.versions).toHaveLength(4)
  const secondPair = workspace.versions.filter(version => version.generationId !== firstPair[0].generationId)
  expect(secondPair).toHaveLength(2)
  const french = secondPair.find(version => version.language?.code === 'fr')!
  const english = secondPair.find(version => version.language?.code === 'en')!
  const switcher = detail.getByLabel('Language version', { exact: true })
  expect((await switcher.locator('option').evaluateAll(options => options.map(option => (option as HTMLOptionElement).value))).sort())
    .toEqual(secondPair.map(version => version.id).sort())
  await expect(switcher).toHaveValue(french.id)
  const unsaved = `${frenchResumeText}\nUNSAVED CONTENT MUST NOT PERSIST`
  await detail.getByRole('button', { name: 'Edit resume', exact: true }).click()
  await detail.getByLabel('Resume text', { exact: true }).fill(unsaved)
  await detail.getByLabel('Version status').selectOption('ready')
  const cancelled = page.waitForEvent('dialog').then(async dialog => {
    expect(dialog.type()).toBe('confirm')
    expect(dialog.message()).toBe('Discard your unsaved changes and switch language versions?')
    await dialog.dismiss()
  })
  await switcher.selectOption(english.id)
  await cancelled
  await expect(switcher).toHaveValue(french.id)
  await expect(detail.getByLabel('Resume text', { exact: true })).toHaveValue(unsaved)
  await expect(detail.getByLabel('Version status')).toHaveValue('ready')
  await expect(detail.getByText('Unsaved changes', { exact: true })).toBeVisible()
  await expect(detail.getByRole('button', { name: 'Export PDF' })).toBeDisabled()
  const discarded = page.waitForEvent('dialog').then(async dialog => {
    expect(dialog.message()).toBe('Discard your unsaved changes and switch language versions?')
    await dialog.accept()
  })
  await switcher.selectOption(english.id)
  await discarded
  await expect(switcher).toHaveValue(english.id)
  await expect(detail.getByRole('article')).toHaveAttribute('lang', 'en')
  await expect(detail.getByRole('article')).not.toContainText('UNSAVED')
  await expect(detail.getByLabel('Version status')).toHaveValue('draft')
  await switcher.selectOption(french.id)
  await expect(detail.getByRole('article')).not.toContainText('UNSAVED')
  await expect(detail.getByLabel('Version status')).toHaveValue('draft')
  await expect(detail.getByRole('button', { name: 'Save changes' })).toBeDisabled()
  const afterDiscard: Workspace = await (await request.get('/api/workspace')).json()
  expect(afterDiscard.versions).toEqual(workspace.versions)
  await detail.getByRole('button', { name: 'Close dialog' }).click()
  await page.reload()
  await expect(page.locator('.version-card')).toHaveCount(4)
  // All four cards share their title/company; each dialog must still contain exactly its pair.
  for (const card of await page.locator('.version-card').all()) {
    await card.click()
    const selectedId = await switcher.inputValue()
    const selected = workspace.versions.find(version => version.id === selectedId)!
    const expectedIds = workspace.versions.filter(version => version.generationId === selected.generationId).map(version => version.id).sort()
    expect((await switcher.locator('option').evaluateAll(options => options.map(option => (option as HTMLOptionElement).value))).sort()).toEqual(expectedIds)
    await detail.getByRole('button', { name: 'Close dialog' }).click()
  }
})

