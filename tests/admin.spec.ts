test('optional password change validates, cancels, handles failure and prevents duplicate submissions', async ({ page, request, expectedHttpErrors }) => {
  await page.getByRole('button', { name: 'Change password', exact: true }).click()
  await expect(page.getByLabel('Current password', { exact: true })).toBeEnabled()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your experience. The right story.' })).toBeVisible()
  await page.getByRole('button', { name: 'Change password', exact: true }).click()
  const current = page.getByLabel('Current password', { exact: true })
  const next = page.getByLabel('New password', { exact: true })
  const confirm = page.getByLabel('Confirm new password', { exact: true })
  const save = page.getByRole('button', { name: 'Save new password', exact: true })
  let submissions = 0
  page.on('request', req => { if (req.url() === `${origin}/api/auth/change-password`) submissions++ })
  await current.fill(testAccount.password)
  await next.fill(secret)
  await confirm.fill(temporary)
  await save.click()
  await expect(page.getByRole('alert')).toHaveText('Passwords do not match.')
  await expect(page.getByRole('alert')).toBeFocused()
  await next.fill(testAccount.password)
  await confirm.fill(testAccount.password)
  await save.click()
  await expect(page.getByRole('alert')).toHaveText('Choose a different new password.')
  expect(submissions).toBe(0)

  expectedHttpErrors.push({ url: `${origin}/api/auth/change-password`, status: 503 })
  await page.route('**/api/auth/change-password', route => route.fulfill({ status: 503, json: { error: 'Temporary service failure.' } }), { times: 1 })
  await next.fill(secret)
  await confirm.fill(secret)
  await save.click()
  await expect(page.getByRole('alert')).toHaveText('Temporary service failure.')
  for (const input of [current, next, confirm]) await expect(input).toHaveValue('')
  await expect(save).toBeEnabled()

  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  let arrived!: () => void
  const intercepted = new Promise<void>(resolve => { arrived = resolve })
  await page.route('**/api/auth/change-password', async route => {
    arrived()
    await gate
    await route.continue()
  }, { times: 1 })
  await current.fill(testAccount.password)
  await next.fill(secret)
  await confirm.fill(secret)
  try {
    await save.click()
    await intercepted
    await expect(save).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeDisabled()
    await page.locator('form').evaluate(form => {
      form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
      form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    })
  } finally { release() }
  await expect(page.getByRole('heading', { name: 'Your experience. The right story.' })).toBeVisible()
  expect(submissions).toBe(2)
  expect((await request.get('/api/auth/session')).status()).toBe(200)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByLabel('Email address').fill(testAccount.identifier)
  await page.getByLabel('Password', { exact: true }).fill(secret)
  await page.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Your experience. The right story.' })).toBeVisible()
  const storage = await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))
  expect(storage).not.toContain(secret)
  expect(storage).not.toContain(testAccount.password)
})

test('password change sign-out errors are shown and can be retried', async ({ page, expectedHttpErrors }) => {
  await page.getByRole('button', { name: 'Change password', exact: true }).click()
  expectedHttpErrors.push({ url: `${origin}/api/auth/logout`, status: 503 })
  await page.route('**/api/auth/logout', route => route.fulfill({ status: 503, json: { error: 'Please retry signing out.' } }), { times: 1 })
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Please retry signing out.')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
})