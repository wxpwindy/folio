const origin = 'http://127.0.0.1:3101'
const initial = 'Example123'
const secret = 'Fictional-administrator-secret!'
const temporary = 'Fictional-reset-secret-2026!'
async function changePassword(page: Page, current: string, next: string) {
  await expect(page.getByRole('heading', { name: 'Change password' })).toBeVisible()
  await page.getByLabel('Current password', { exact: true }).fill(current)
  await page.getByLabel('New password', { exact: true }).fill(next)
  await page.getByLabel('Confirm new password', { exact: true }).fill(next)
  const response = page.waitForResponse(`${origin}/api/auth/change-password`)
  await page.getByRole('button', { name: 'Save new password' }).click()
  expect((await response).status()).toBe(200)
  await expect(page.getByRole('heading', { name: 'Your experience. The right story.' })).toBeVisible()
}

