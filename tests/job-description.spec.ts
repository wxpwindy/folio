import { test, expect, uploadResume, pdfBuffer, expectNoOverflow } from './helpers.ts'
import { jobDescription } from './data.ts'

test('cover-letter JD uploads clear cloud consent and server failures preserve the draft', async ({ page, expectedHttpErrors }) => {
  expectedHttpErrors.push('http://127.0.0.1:3101/api/job-description/extract')
  await uploadResume(page)
  await page.getByRole('button', { name: 'AI settings', exact: true }).click()
  await page.getByRole('button', { name: /OpenAI Cloud processing/ }).click()
  await page.getByRole('button', { name: 'Save settings' }).click()
  await page.getByRole('button', { name: 'New cover letter', exact: true }).click()
  const form = page.getByRole('dialog')
  const text = form.getByLabel('Job description', { exact: true })
  const file = form.getByLabel('Upload JD document', { exact: true })
  const consent = form.getByRole('checkbox')
  await text.fill(jobDescription)
  await consent.check()
  page.once('dialog', dialog => dialog.accept())
  await file.setInputFiles({ name: 'damaged.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-damaged') })
  await expect(form.getByRole('alert')).toContainText('could not be read')
  await expect(text).toHaveValue(jobDescription)
  await expect(consent).not.toBeChecked()
  await consent.check()
  page.once('dialog', dialog => dialog.accept())
  await file.setInputFiles({ name: 'job.txt', mimeType: 'text/plain', buffer: Buffer.from(jobDescription) })
  await expect(form.getByText('Imported job.txt.', { exact: false })).toBeVisible()
  await expect(consent).not.toBeChecked()
  await consent.check()
  await text.fill(`${jobDescription} Edited.`)
  await expect(consent).not.toBeChecked()
})

test('JD PDF upload is editable and used for generation at 320px', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 900 })
  await uploadResume(page)
  await page.getByRole('button', { name: 'New version', exact: true }).click()
  const form = page.getByRole('dialog')
  await form.getByLabel('Job title', { exact: true }).fill('Frontend Engineer')
  await form.getByLabel('Company', { exact: true }).fill('Example Labs')
  await form.getByLabel('Upload JD document', { exact: true }).setInputFiles({ name: 'job.pdf', mimeType: 'application/pdf', buffer: await pdfBuffer(jobDescription) })
  const text = form.getByLabel('Job description', { exact: true })
  await expect(form.getByText('Imported job.pdf.', { exact: false })).toBeVisible()
  expect((await text.inputValue()).replace(/\s+/g, ' ')).toBe(jobDescription.replace(/\s+/g, ' '))
  const edited = `${jobDescription}\nAdditional requirement: code review.`
  await text.fill(edited)
  await expectNoOverflow(page)
  const generated = page.waitForResponse(response => response.url().endsWith('/api/versions') && response.request().method() === 'POST')
  await form.getByRole('button', { name: 'Generate version', exact: true }).click()
  expect((await (await generated).json()).jobDescription).toBe(edited)
})

test('JD uploads preserve drafts on failure/cancel and block edits during extraction', async ({ page }) => {
  await uploadResume(page)
  await page.getByRole('button', { name: 'New version', exact: true }).click()
  const form = page.getByRole('dialog')
  const text = form.getByLabel('Job description', { exact: true })
  const file = form.getByLabel('Upload JD document', { exact: true })
  await text.fill(jobDescription)
  await file.setInputFiles({ name: 'job.docx', mimeType: 'application/octet-stream', buffer: Buffer.from('invalid') })
  await expect(form.getByRole('alert')).toContainText('Upload a PDF')
  await expect(text).toHaveValue(jobDescription)
  page.once('dialog', dialog => dialog.dismiss())
  await file.setInputFiles({ name: 'job.txt', mimeType: 'text/plain', buffer: Buffer.from('replacement') })
  await expect(text).toHaveValue(jobDescription)
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/job-description/extract', async route => { await gate; await route.continue() })
  page.once('dialog', dialog => dialog.accept())
  await file.setInputFiles({ name: 'job.txt', mimeType: 'text/plain', buffer: Buffer.from('Short editable JD') })
  await expect(text).toBeDisabled()
  await expect(form.getByRole('button', { name: 'Close dialog' })).toBeDisabled()
  await expect(form.getByRole('button', { name: 'Extracting document…', exact: true })).toBeDisabled()
  release()
  await expect(text).toHaveValue('Short editable JD')
  await expect(text).toBeEnabled()
  await form.getByLabel('Job title', { exact: true }).fill('Engineer')
  await form.getByLabel('Company', { exact: true }).fill('Example')
  await form.getByRole('button', { name: 'Generate version' }).click()
  await expect(form.getByRole('alert')).toContainText('at least 80 characters')
})

test('AI settings checks Ollama and saves a selected installed model', async ({ page }) => {
  await page.route('**/api/ollama/models', route => route.fulfill({ json: { models: ['installed-local-model'] } }))
  await page.getByRole('button', { name: 'AI settings', exact: true }).click()
  const form = page.getByRole('dialog')
  await form.getByRole('button', { name: 'Check connection' }).click()
  await expect(form.getByRole('status')).toContainText('Ollama is connected')
  await form.getByLabel('Installed Ollama models').selectOption('installed-local-model')
  await form.getByRole('button', { name: 'Save settings' }).click()
  await page.getByRole('button', { name: 'AI settings', exact: true }).click()
  await expect(page.getByLabel('Ollama model', { exact: true })).toHaveValue('installed-local-model')
})