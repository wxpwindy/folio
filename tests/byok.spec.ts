import { test, expect, uploadResume, expectNoOverflow, testSettingsKey, testAccount } from './helpers.ts'
import type { Page } from '@playwright/test'
import type { Workspace } from '../src/types.ts'
import { jobDescription } from './data.ts'

const baseUrl = 'https://api.example.com/v1'
const model = 'fictional/custom-chat-model'
const fakeKey = 'fictional-byok-key-not-a-secret'

async function openSettings(page: Page) {
  await page.getByRole('button', { name: 'Open AI settings', exact: true }).click()
  return page.getByRole('dialog', { name: 'Your AI, your choice.' })
}

async function configureByok(page: Page) {
  const settings = await openSettings(page)
  await settings.getByRole('button', { name: 'BYOK Your own model', exact: true }).click()
  await settings.getByLabel('API base URL', { exact: true }).fill(`${baseUrl}/`)
  await settings.getByLabel('BYOK model', { exact: true }).fill(model)
  await settings.getByLabel('BYOK API key', { exact: true }).fill(fakeKey)
  await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
}

test('BYOK settings preserve non-secret preferences, isolate keys, and clear keys on destination change and reload', async ({ page, context, request }) => {
  await uploadResume(page)
  let settings = await openSettings(page)
  await settings.getByRole('button', { name: 'OpenAI Cloud processing', exact: true }).click()
  await settings.getByLabel(/^API key/).fill('fictional-openai-only-key')
  await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
  await configureByok(page)
  settings = await openSettings(page)
  await expect(settings.getByLabel('BYOK API key', { exact: true })).toHaveValue(fakeKey)
  await expect(settings.getByLabel('BYOK API key', { exact: true })).toHaveAttribute('type', 'password')
  await expect(settings.getByLabel('API base URL', { exact: true })).toHaveValue(baseUrl)
  await settings.getByRole('button', { name: 'OpenAI Cloud processing', exact: true }).click()
  await expect(settings.getByLabel(/^API key/)).toHaveValue('fictional-openai-only-key')
  await settings.getByRole('button', { name: 'BYOK Your own model', exact: true }).click()
  await settings.getByLabel('API base URL', { exact: true }).fill('https://other.example.com/v1')
  await expect(settings.getByLabel('BYOK API key', { exact: true })).toHaveValue('')
  await settings.getByRole('button', { name: 'Cancel', exact: true }).click()
  const storage = await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))
  expect(JSON.parse(storage.local[testSettingsKey])).toMatchObject({ provider: 'byok', byokBaseUrl: baseUrl, byokModel: model })
  for (const value of [storage, await context.cookies(), await (await request.get('/api/workspace')).json()]) {
    expect(JSON.stringify(value)).not.toContain(fakeKey)
    expect(JSON.stringify(value)).not.toContain('fictional-openai-only-key')
    expect(JSON.stringify(value)).not.toMatch(/cloudConsent|"consent"/)
  }
  await page.reload()
  settings = await openSettings(page)
  await expect(settings.getByRole('button', { name: 'BYOK Your own model', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(settings.getByLabel('API base URL', { exact: true })).toHaveValue(baseUrl)
  await expect(settings.getByLabel('BYOK model', { exact: true })).toHaveValue(model)
  await expect(settings.getByLabel('BYOK API key', { exact: true })).toHaveValue('')
})

test('BYOK rejects unsafe URL syntax before saving and remains usable at 320px', async ({ page }) => {
  await uploadResume(page)
  await page.setViewportSize({ width: 320, height: 900 })
  const settings = await openSettings(page)
  await settings.getByRole('button', { name: 'BYOK Your own model', exact: true }).click()
  await settings.getByLabel('BYOK model', { exact: true }).fill(model)
  for (const url of ['http://api.example.com/v1', 'https://user:password@api.example.com/v1', 'https://api.example.com/v1?key=fictional', 'https://api.example.com/v1#fragment']) {
    await settings.getByLabel('API base URL', { exact: true }).fill(url)
    await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
    await expect(settings.getByRole('alert')).toContainText('Use an HTTPS API base URL without credentials')
    expect(await page.evaluate(key => localStorage.getItem(key), testSettingsKey)).not.toContain(url)
  }
  await expectNoOverflow(page)
  await settings.getByLabel('API base URL', { exact: true }).fill(baseUrl)
  await settings.getByLabel('BYOK API key', { exact: true }).fill(fakeKey)
  await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
  await page.getByRole('button', { name: 'Translate to Chinese', exact: true }).click()
  const translation = page.getByRole('dialog', { name: 'Translate document', exact: true })
  await expect(translation.locator('.generation-provider')).toContainText(baseUrl)
  await expectNoOverflow(page)
})

test('BYOK wires consent and credentials through tailoring, cover letters, cleanup and translation without storing them', async ({ page, request }) => {
  await uploadResume(page)
  await configureByok(page)
  for (const documentType of ['resume', 'cover-letter']) {
    await page.getByRole('button', { name: 'New version', exact: true }).click()
    const form = page.getByRole('dialog')
    await form.getByLabel('Document type', { exact: true }).selectOption(documentType)
    await form.getByLabel('Job title', { exact: true }).fill('Frontend Engineer')
    await form.getByLabel('Company', { exact: true }).fill('Example Labs')
    await form.getByLabel('Job description', { exact: true }).fill(jobDescription)
    await expect(form.locator('.generation-provider')).toContainText(`BYOK (${baseUrl})`)
    const consent = form.getByRole('checkbox')
    await expect(consent).not.toBeChecked()
    await expect(consent).toHaveAttribute('required', '')
    await consent.check()
    await form.getByLabel('Job description', { exact: true }).fill(`${jobDescription}\nUpdated requirements.`)
    await expect(consent).not.toBeChecked()
    await consent.check()
    const pending = page.waitForRequest(req => req.url().endsWith('/api/versions') && req.method() === 'POST')
    await form.getByRole('button', { name: documentType === 'resume' ? 'Generate version' : 'Generate cover letter', exact: true }).click()
    expect((await pending).postDataJSON()).toMatchObject({ provider: 'byok', model, baseUrl, apiKey: fakeKey, cloudConsent: true, documentType })
    await expect(page.locator('.model-credit')).toHaveText(`BYOK · ${model}`)
    await page.getByRole('button', { name: 'Close dialog', exact: true }).click()
  }
  await page.getByRole('button', { name: 'Base resume', exact: true }).click()
  await page.getByRole('button', { name: 'Create clean English + Chinese', exact: true }).click()
  const clean = page.getByRole('dialog', { name: 'Create clean base resumes' })
  await expect(clean.getByRole('button', { name: 'Generate both versions', exact: true })).toBeDisabled()
  await clean.getByRole('checkbox').check()
  const cleaning = page.waitForRequest(req => req.url().endsWith('/api/base/clean'))
  await clean.getByRole('button', { name: 'Generate both versions', exact: true }).click()
  expect((await cleaning).postDataJSON()).toMatchObject({ provider: 'byok', model, baseUrl, apiKey: fakeKey, cloudConsent: true })
  await page.getByRole('dialog', { name: 'Clean base resume', exact: true }).getByRole('button', { name: 'Close dialog', exact: true }).click()
  await page.getByRole('button', { name: 'Translate to Chinese', exact: true }).click()
  const translation = page.getByRole('dialog', { name: 'Translate document', exact: true })
  await expect(translation.getByRole('button', { name: 'Translate document', exact: true })).toBeDisabled()
  await translation.getByRole('checkbox').check()
  await translation.getByLabel(/^BYOK API key/).fill('fictional-per-translation-key')
  await expect(translation.getByRole('checkbox')).not.toBeChecked()
  await translation.getByRole('checkbox').check()
  const translating = page.waitForRequest(req => req.url().endsWith('/api/translations'))
  await translation.getByRole('button', { name: 'Translate document', exact: true }).click()
  expect((await translating).postDataJSON()).toMatchObject({ provider: 'byok', model, baseUrl, apiKey: 'fictional-per-translation-key', cloudConsent: true })
  await expect(page.locator('.model-credit')).toHaveText(`BYOK · ${model}`)
  const workspace: Workspace = await (await request.get('/api/workspace')).json()
  expect(workspace.versions).toHaveLength(5)
  expect(workspace.versions.every(version => version.provider === 'byok' && version.model === model)).toBe(true)
  expect(JSON.stringify(workspace)).not.toContain(fakeKey)
  expect(JSON.stringify(workspace)).not.toContain('fictional-per-translation-key')
  expect(JSON.stringify(workspace)).not.toContain(baseUrl)
})

test('BYOK survives an LM Studio default and logout preserves preferences but clears its key', async ({ page, request }) => {
  await uploadResume(page)
  await page.evaluate(({ key, url, model }) => localStorage.setItem(key, JSON.stringify({ provider: 'byok', byokBaseUrl: url, byokModel: model })), { key: testSettingsKey, url: baseUrl, model })
  await page.route('**/api/workspace', async route => {
    const response = await route.fetch()
    const body: Workspace = await response.json()
    await route.fulfill({ response, json: { ...body, config: { ...body.config, defaultProvider: 'lmstudio', openaiConfigured: true } } })
  })
  await page.reload()
  let settings = await openSettings(page)
  await expect(settings.getByRole('button', { name: 'BYOK Your own model', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
  await page.getByRole('button', { name: 'Base resume', exact: true }).click()
  await page.getByRole('button', { name: 'Translate to Chinese', exact: true }).click()
  const translation = page.getByRole('dialog', { name: 'Translate document', exact: true })
  await translation.getByRole('checkbox').check()
  await expect(translation.getByRole('button', { name: 'Translate document', exact: true })).toBeDisabled()
  await translation.getByRole('button', { name: 'Cancel', exact: true }).click()
  settings = await openSettings(page)
  await settings.getByLabel('BYOK API key', { exact: true }).fill(fakeKey)
  await settings.getByRole('button', { name: 'Save settings', exact: true }).click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back' })).toBeVisible()
  const login = await request.post('/api/auth/login', { data: { method: testAccount.method, identifier: testAccount.identifier, password: testAccount.password } })
  expect(login.status()).toBe(200)
  await page.reload()
  settings = await openSettings(page)
  await expect(settings.getByLabel('BYOK API key', { exact: true })).toHaveValue('')
  await expect(settings.getByLabel('BYOK model', { exact: true })).toHaveValue(model)
})
